"""Prompts for LoRA rule extraction — mirror scripts/prompts.py byte-for-byte."""

from .vocab import _AUDIENCES
from ...core.topics import ALLOWED_TOPICS

_SYSTEM_PROMPT = (
    "Ты — эксперт по ИБ и методист корпоративного обучения. "
    "Извлекаешь из регламентов ТОЛЬКО те правила, из которых можно построить "
    "обучающий сценарий для сотрудников: ситуация → правильное действие. "
    "Отвечай ТОЛЬКО на русском."
)

_INSTRUCTION = (
    "Извлеки из фрагмента регламента ТОЛЬКО правила, пригодные для "
    "обучающих сценариев по информационной безопасности.\n\n"
    "ФОРМАТ ВЫВОДА — строго одна строка на правило, без пояснений:\n"
    "audience=<код> | topic=<тема> | <текст правила>\n\n"
    "audience — это КОГО НУЖНО ОБУЧИТЬ правилу. Определяй по подлежащему.\n"
    "Конкретные роли (из списка AUDIENCES) — ставь их код."
    "«системный администратор», «администратор системы» → it; "
    "«администратор безопасности», «ответственный за ИБ» → security; "
    "«руководитель», «директор», «заведующий» → management; "
    "«подрядчик», «контрагент» → contractors; «стажёр» → interns.\n"
    "general — если подлежащее «работник», «сотрудник», «пользователь», "
    "«персонал» без уточнения отдела, или неодушевлённое подлежащее "
    "(пароль, PIN, токен, документ, устройство, носитель), или правило "
    "о паролях, интернете, почте, инцидентах, документах, экране.\n"
    "other — если правило не про сотрудника (описание системы/процесса).\n"
    "Несколько ролей — через запятую, без пробела.\n"
    "Текст правила — дословная цитата из фрагмента. НЕ перефразируй, "
    "НЕ сокращай, НЕ дополняй своими словами. Если правило составное "
    "(действие + уточнение), разрешено склеить два соседних предложения "
    "через пробел.\n\n"
    "Правило ПОДХОДИТ, если:\n"
    "1. Описывает действие сотрудника в конкретной ситуации "
    "(что делать / чего не делать).\n"
    "2. Из него можно составить сценарий: «Ситуация → правильное действие».\n"
    "3. Сформулировано как требование, запрет или обязанность для сотрудника.\n"
    "4. Это завершённая мысль — не обрывок, не часть составного правила.\n\n"
    "Правило НЕ ПОДХОДИТ (пропусти):\n"
    "- Определение: «X — это Y», «X — совокупность Z».\n"
    "- Ссылка на ФЗ, ГОСТ, приказ, Политику, Стандарт или иной документ.\n"
    "- Заголовок раздела: «Приём посетителей», «Доступ в помещения».\n"
    "- Общая административная процедура без поведенческого контекста: "
    "«Работники знакомятся с Политикой под подпись», «X утверждает Y».\n"
    "- Описание системы/процесса вместо действия сотрудника: "
    "«На табло отображается…», «Система поддерживает работоспособное состояние».\n"
    "- Специфическая техническая инструкция для администраторов: "
    "«После восстановления системы временные записи сверяются…».\n"
    "- Фрагменты: контакты, реквизиты, номера телефонов, перечни лиц.\n\n"
    "Требования к выводу: одна строка на правило, без пояснений. "
    "Текст правила — ТОЧНАЯ цитата из фрагмента (можно склеить два соседних "
    "предложения, если они образуют одно правило).\n\n"
    f"Допустимые audience:\n{_AUDIENCES}\n\n"
    f"Допустимые topic: {', '.join(ALLOWED_TOPICS)}"
)


def _build_user_prompt(chunk_text: str) -> str:
    """Assemble the user-message for one chunk (mirror scripts/prompts.py)."""
    return f"{_INSTRUCTION}\n\nФрагмент:\n{chunk_text}"
